/**
 * 所有词牌名合并集合（包含变体）
 */
private val ALL_CI_TITLES: Set<String> = buildSet {
    addAll(CI_TITLES_2_CHAR)
    addAll(CI_TITLES_3_CHAR)
    addAll(CI_TITLES_4_CHAR)
    addAll(CI_TITLES_MULTI)
    CI_TITLE_VARIANTS.values.forEach { variants ->
        addAll(variants)
    }
}

/**
 * 检测诗词类型
 * 综合策略：
 * 1. 标题检测：带有"·"等分隔符的才是词牌名（如"扬州慢·淮左名都"）
 * 2. 内容格式检测：诗句长固定，词句长变化大
 *
 * @param title 诗词标题
 * @param content 诗词内容
 * @return 诗词类型
 */
fun detectPoemType(
    title: String,
    content: String = ""
): PoemType {
    val cleanTitle = title.trim()

    // 策略1：标题检测
    // 词牌名标题通常带有分隔符"·"，如"扬州慢·淮左名都"
    // 如果标题以"词牌名·内容"格式，直接判断为词
    for (ciTitle in ALL_CI_TITLES) {
        if (cleanTitle.startsWith(ciTitle) && cleanTitle.length > ciTitle.length) {
            val nextChar = cleanTitle[ciTitle.length]
            if (nextChar in "· （(【《") {
                return PoemType.CI
            }
        }
        // 标题完全等于词牌名
        if (cleanTitle == ciTitle) {
            // 需要进一步通过内容判断
            break
        }
    }

    // 策略2：内容格式检测（主要判断依据）
    if (content.isNotEmpty()) {
        val lines = content.split("\n").filter { it.isNotBlank() }
        if (lines.size >= 2) {
            val lineLengths = lines.map { it.trim().length }

            // 诗的特征：每句字数相同（支持五言、七言绝句/律诗）
            val isUniformLength = lineLengths.distinct().size == 1

            // 词的特征：句长短不一（差异超过2个字）
            val lengthRange = (lineLengths.maxOrNull() ?: 0) - (lineLengths.minOrNull() ?: 0)
            val hasVaryingLength = lineLengths.distinct().size > 1 && lengthRange > 2

            if (isUniformLength) {
                return PoemType.POEM
            }

            if (hasVaryingLength) {
                return PoemType.CI
            }
        }
    }

    // 默认返回诗
    return PoemType.POEM
}
